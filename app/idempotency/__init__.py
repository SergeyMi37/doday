"""Повторная отправка запроса не должна делать работу дважды.

Зачем это нужно. Телефон в школе или в метро теряет сеть в самый неподходящий
момент — ровно между «запрос ушёл» и «ответ пришёл». Клиент в этот момент
знает только одно: ответа нет. Создалась задача или нет — ему неизвестно.

Вариантов у клиента два, и оба плохие: не повторять (тогда действие человека
пропало) или повторять (тогда в списке появятся две одинаковые задачи).

Выход — дать запросу имя. Клиент придумывает ключ (`Idempotency-Key`),
кладёт его в заголовок и с этим же ключом повторяет запрос сколько угодно
раз. Сервер выполняет работу только под первым ключом, а на повторы отдаёт
тот же ответ, что и в первый раз.

Так делают платёжные API — Stripe, YooKassa, — и по той же причине: там цена
задвоения выше, чем просто раздражение.

Устройство: `app/idempotency/middleware.py` — перехват запроса,
`app/idempotency/models.py` — где хранятся ключи и ответы.
"""
